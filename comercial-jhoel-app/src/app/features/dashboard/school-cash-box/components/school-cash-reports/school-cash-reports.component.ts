import { ChangeDetectionStrategy, Component, OnInit, computed, inject, signal } from '@angular/core';
import { HttpErrorResponse } from '@angular/common/http';
import { FormsModule } from '@angular/forms';

import { SchoolCashReport, SchoolCashReportInfo, SchoolCashReportValue, formatCurrency } from '../../../../../core/models';
import { SchoolCashBoxService } from '../../../../../core/services/school-cash-box.service';
import { NotificationService } from '../../../../../core/services/notification.service';
import { downloadBlob } from '../../../../../core/utils/download-blob';
import { extractErrorMessage } from '../../../../../core/utils/extract-error-message';
import { ButtonComponent, IconComponent } from '../../../../../shared/ui';
import { formatGuatemalaDateTime, formatIsoDate, guatemalaToday, monthStart } from '../../school-cash.util';

const REPORT_ICON: Record<string, string> = {
  'recaudacion-diaria': 'calendar',
  'recaudacion-cliente': 'users',
  'recaudacion-lista': 'graduation-cap',
  'pagos-efectivo': 'wallet',
  'pagos-bancarios': 'bank',
  traslados: 'arrow-down-circle',
  'pendiente-traslado': 'clock',
  arqueos: 'file-check',
  salidas: 'log-out',
  'saldos-clientes': 'alert-circle',
  movimientos: 'layers',
  'cartera-clientes': 'users',
  // Quoted vs accepted vs collected per list (migration 1760009000000).
  'estado-listas': 'file-check',
};

/**
 * Reports of the Caja de Listas: pick a report and a period, see the same
 * rows the backend exports, and download them as PDF or Excel (generated by
 * the backend with the existing report infrastructure).
 */
@Component({
  selector: 'app-school-cash-reports',
  standalone: true,
  imports: [FormsModule, ButtonComponent, IconComponent],
  templateUrl: './school-cash-reports.component.html',
  styleUrl: './school-cash-reports.component.scss',
  changeDetection: ChangeDetectionStrategy.OnPush,
})
export class SchoolCashReportsComponent implements OnInit {
  private readonly service = inject(SchoolCashBoxService);
  private readonly notifications = inject(NotificationService);

  iconOf(kind: string): string {
    return REPORT_ICON[kind] || 'bar-chart';
  }
  readonly formatCurrency = formatCurrency;
  readonly catalog = signal<SchoolCashReportInfo[]>([]);
  readonly kind = signal('recaudacion-diaria');
  readonly dateFrom = signal(monthStart(guatemalaToday()));
  readonly dateTo = signal(guatemalaToday());
  readonly report = signal<SchoolCashReport | null>(null);
  readonly loading = signal(false);
  readonly error = signal<string | null>(null);
  readonly exporting = signal<'pdf' | 'xlsx' | null>(null);

  readonly current = computed(() => this.catalog().find((r) => r.kind === this.kind()) ?? null);
  readonly hasTotals = computed(() => this.report()?.columns.some((c) => c.total) ?? false);

  ngOnInit(): void {
    this.service.getReports().subscribe({
      next: (catalog) => {
        this.catalog.set(catalog);
        this.load();
      },
      error: (err: HttpErrorResponse) => this.error.set(extractErrorMessage(err, 'No se pudieron cargar los reportes.')),
    });
  }

  choose(kind: string): void {
    this.kind.set(kind);
    this.load();
  }

  load(): void {
    this.loading.set(true);
    this.error.set(null);
    this.service.getReport(this.kind(), this.range()).subscribe({
      next: (report) => {
        this.report.set(report);
        this.loading.set(false);
      },
      error: (err: HttpErrorResponse) => {
        this.loading.set(false);
        this.report.set(null);
        this.error.set(extractErrorMessage(err, 'No se pudo generar el reporte.'));
      },
    });
  }

  download(format: 'pdf' | 'xlsx'): void {
    if (this.exporting()) {
      return;
    }
    this.exporting.set(format);
    const range = this.range();
    this.service.exportReport(this.kind(), format, range).subscribe({
      next: (blob) => {
        this.exporting.set(null);
        downloadBlob(blob, `caja-listas-${this.kind()}-${range.dateFrom}_${range.dateTo}.${format}`);
      },
      error: () => {
        this.exporting.set(null);
        this.notifications.error('No se pudo exportar el reporte.');
      },
    });
  }

  cell(type: string, value: SchoolCashReportValue): string {
    if (value === null || value === undefined || value === '') {
      return type === 'money' ? formatCurrency(0) : '—';
    }
    switch (type) {
      case 'money':
        return formatCurrency(Number(value));
      case 'date':
        return formatIsoDate(String(value).slice(0, 10));
      case 'datetime':
        return formatGuatemalaDateTime(String(value));
      default:
        return String(value);
    }
  }

  private range(): { dateFrom: string; dateTo: string } {
    return { dateFrom: this.dateFrom(), dateTo: this.dateTo() };
  }
}
