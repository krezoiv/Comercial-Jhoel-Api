import { ChangeDetectionStrategy, Component, OnInit, computed, inject, signal } from '@angular/core';
import { HttpErrorResponse } from '@angular/common/http';
import { FormsModule } from '@angular/forms';
import { ActivatedRoute, RouterLink } from '@angular/router';

import {
  SCHOOL_CUSTOMER_STATUS_TONE,
  SCHOOL_LIST_ACCOUNT_LABEL,
  SchoolCustomerList,
  SchoolCustomerStatement,
  SchoolQuotationStatus,
  SchoolQuotationSummary,
  canReceiveSchoolPayment,
  formatCurrency,
  paymentDestinationLabel,
} from '../../../../core/models';
import { SchoolCashBoxService } from '../../../../core/services/school-cash-box.service';
import { SchoolListService } from '../../../../core/services/school-list.service';
import { NotificationService } from '../../../../core/services/notification.service';
import { downloadBlob } from '../../../../core/utils/download-blob';
import { extractErrorMessage } from '../../../../core/utils/extract-error-message';
import { ButtonComponent, IconComponent } from '../../../../shared/ui';
import { SchoolPaymentModalComponent } from '../../school-lists/components/school-payment-modal/school-payment-modal.component';
import { formatGuatemalaDateTime, formatIsoDate } from '../school-cash.util';
import { CustomerListChooserComponent } from './customer-list-chooser.component';

const LIST_TONE: Record<string, string> = {
  PAGADA: 'cash',
  PARCIAL: 'pending',
  PENDIENTE: 'owed',
  CANCELADA: 'neutral',
  BORRADOR: 'neutral',
};

/**
 * The financial file of ONE customer (every list with the same phone
 * digits): who they are, what they bought, paid and owe, each list per child,
 * every payment with where its money went, and the chronological statement
 * rebuilt from real records. "Registrar abono" reuses the official payment
 * modal (same endpoint, same rules) on the list the user chooses; the PDF is
 * generated by the backend.
 */
@Component({
  selector: 'app-school-cash-customer-page',
  standalone: true,
  imports: [FormsModule, RouterLink, ButtonComponent, IconComponent, SchoolPaymentModalComponent, CustomerListChooserComponent],
  templateUrl: './school-cash-customer-page.component.html',
  styleUrl: './school-cash-customer-page.component.scss',
  changeDetection: ChangeDetectionStrategy.OnPush,
})
export class SchoolCashCustomerPageComponent implements OnInit {
  private readonly route = inject(ActivatedRoute);
  private readonly service = inject(SchoolCashBoxService);
  private readonly notifications = inject(NotificationService);
  readonly lists = inject(SchoolListService);

  readonly formatCurrency = formatCurrency;
  readonly formatDateTime = formatGuatemalaDateTime;
  readonly formatDay = formatIsoDate;
  readonly statusTone = SCHOOL_CUSTOMER_STATUS_TONE;
  readonly listLabel = SCHOOL_LIST_ACCOUNT_LABEL;
  readonly listTone = LIST_TONE;
  readonly destination = paymentDestinationLabel;

  readonly key = signal('');
  readonly data = signal<SchoolCustomerStatement | null>(null);
  readonly loading = signal(true);
  readonly error = signal<string | null>(null);
  readonly ledgerFrom = signal('');
  readonly ledgerTo = signal('');
  readonly choosing = signal(false);
  readonly paying = signal<SchoolQuotationSummary | null>(null);
  readonly printing = signal(false);
  readonly openPayment = signal<string | null>(null);

  readonly canView = computed(() => this.lists.permissionsLoaded() && this.lists.can('school_lists.customers.view'));
  readonly canPay = computed(() => this.lists.can('school_lists.payments.register'));
  readonly canPrint = computed(() => this.lists.can('school_lists.customers.export'));
  readonly payable = computed(() =>
    (this.data()?.lists ?? []).filter((l) => l.balance > 0 && canReceiveSchoolPayment(l.status as SchoolQuotationStatus)),
  );
  readonly progress = computed(() => this.data()?.customer.percentPaid ?? 0);

  ngOnInit(): void {
    this.key.set(this.route.snapshot.paramMap.get('key') ?? '');
    const start = () => this.load();
    if (this.lists.permissionsLoaded()) {
      start();
    } else {
      this.lists.loadPermissions().subscribe({ next: start, error: () => this.error.set('No se pudieron cargar sus permisos.') });
    }
  }

  load(): void {
    if (!this.canView()) {
      this.loading.set(false);
      return;
    }
    this.loading.set(true);
    this.service
      .getCustomer(this.key(), { dateFrom: this.ledgerFrom() || undefined, dateTo: this.ledgerTo() || undefined })
      .subscribe({
        next: (data) => {
          this.data.set(data);
          this.loading.set(false);
          this.error.set(null);
        },
        error: (err: HttpErrorResponse) => {
          this.loading.set(false);
          this.error.set(extractErrorMessage(err, 'No se pudo cargar el estado de cuenta.'));
        },
      });
  }

  clearLedgerRange(): void {
    this.ledgerFrom.set('');
    this.ledgerTo.set('');
    this.load();
  }

  /** One payable list: straight to the payment; several: the user chooses. */
  registerPayment(): void {
    const lists = this.payable();
    if (lists.length === 1) {
      this.pay(lists[0]);
    } else if (lists.length > 1) {
      this.choosing.set(true);
    }
  }

  /** The official payment modal reads the list number, customer, grade and amounts. */
  pay(list: SchoolCustomerList): void {
    this.choosing.set(false);
    this.paying.set({
      id: list.id,
      quotationNumber: list.quotationNumber,
      customerName: this.data()?.customer.name ?? '',
      grade: list.grade,
      total: list.total,
      paid: list.paid,
      balance: list.balance,
    } as SchoolQuotationSummary);
  }

  paid(): void {
    this.paying.set(null);
    this.load();
  }

  print(): void {
    if (this.printing()) {
      return;
    }
    this.printing.set(true);
    this.service.getCustomerStatementPdf(this.key()).subscribe({
      next: (blob) => {
        this.printing.set(false);
        const url = URL.createObjectURL(blob);
        const tab = window.open(url, '_blank');
        if (!tab) {
          downloadBlob(blob, `estado-de-cuenta-${this.key()}.pdf`);
        }
        setTimeout(() => URL.revokeObjectURL(url), 60_000);
      },
      error: () => {
        this.printing.set(false);
        this.notifications.error('No se pudo generar el estado de cuenta.');
      },
    });
  }

  listPercent(list: SchoolCustomerList): number {
    return list.total > 0 && list.status !== 'CANCELADA' ? Math.min(100, (list.paid / list.total) * 100) : 0;
  }

  togglePayment(id: string): void {
    this.openPayment.update((current) => (current === id ? null : id));
  }
}
