import { HttpClient, HttpParams } from '@angular/common/http';
import { Injectable, inject } from '@angular/core';
import { Observable, map } from 'rxjs';

import { environment } from '../../../environments/environment';
import {
  ApiSuccessResponse,
  SchoolCashCount,
  SchoolCashExit,
  SchoolCashExitDestination,
  SchoolCashMovement,
  SchoolCashMovementFilters,
  SchoolCashPage,
  SchoolCashReceipt,
  SchoolCashReport,
  SchoolCashReportInfo,
  SchoolCashSummary,
  SchoolCashTransfer,
  SchoolCashGranularity,
  SchoolCustomerFilters,
  SchoolCustomerPage,
  SchoolCustomerStatement,
  SchoolPaymentFilters,
  SchoolPaymentPage,
} from '../models';

const BASE_URL = `${environment.apiUrl}/school-cash-box`;

function toParams(filters: object): HttpParams {
  let params = new HttpParams();
  for (const [key, value] of Object.entries(filters)) {
    if (value !== undefined && value !== null && value !== '') {
      params = params.set(key, String(value));
    }
  }
  return params;
}

export interface SchoolCashRange {
  dateFrom?: string;
  dateTo?: string;
  page?: number;
  limit?: number;
}

/**
 * HTTP client of the Caja de Listas Escolares. Permissions come from the
 * Listas Escolares permission set (`SchoolListService.can('school_lists.cash.*')`);
 * the backend enforces them again in every use case and SQL function.
 */
@Injectable({ providedIn: 'root' })
export class SchoolCashBoxService {
  private readonly http = inject(HttpClient);

  getSummary(
    period: { dateFrom?: string; dateTo?: string; granularity?: SchoolCashGranularity } = {},
  ): Observable<SchoolCashSummary> {
    return this.http
      .get<ApiSuccessResponse<SchoolCashSummary>>(`${BASE_URL}/summary`, { params: toParams(period) })
      .pipe(map((r) => r.data));
  }

  getCustomers(filters: SchoolCustomerFilters): Observable<SchoolCustomerPage> {
    return this.http
      .get<ApiSuccessResponse<SchoolCustomerPage>>(`${BASE_URL}/customers`, { params: toParams(filters) })
      .pipe(map((r) => r.data));
  }

  /** `key` = phone digits of the customer. */
  getCustomer(key: string, range: { dateFrom?: string; dateTo?: string } = {}): Observable<SchoolCustomerStatement> {
    return this.http
      .get<ApiSuccessResponse<SchoolCustomerStatement>>(`${BASE_URL}/customers/${encodeURIComponent(key)}`, {
        params: toParams(range),
      })
      .pipe(map((r) => r.data));
  }

  /** Printable statement (PDF generated by the backend). */
  getCustomerStatementPdf(key: string): Observable<Blob> {
    return this.http.get(`${BASE_URL}/customers/${encodeURIComponent(key)}/statement`, { responseType: 'blob' });
  }

  getPayments(filters: SchoolPaymentFilters): Observable<SchoolPaymentPage> {
    return this.http
      .get<ApiSuccessResponse<SchoolPaymentPage>>(`${BASE_URL}/payments`, { params: toParams(filters) })
      .pipe(map((r) => r.data));
  }

  getMovements(filters: SchoolCashMovementFilters): Observable<SchoolCashPage<SchoolCashMovement>> {
    return this.http
      .get<ApiSuccessResponse<SchoolCashPage<SchoolCashMovement>>>(`${BASE_URL}/movements`, { params: toParams(filters) })
      .pipe(map((r) => r.data));
  }

  getMovement(id: string): Observable<SchoolCashMovement> {
    return this.http.get<ApiSuccessResponse<SchoolCashMovement>>(`${BASE_URL}/movements/${id}`).pipe(map((r) => r.data));
  }

  getUsers(): Observable<{ id: string; name: string }[]> {
    return this.http.get<ApiSuccessResponse<{ id: string; name: string }[]>>(`${BASE_URL}/users`).pipe(map((r) => r.data));
  }

  getReceipts(filters: { bankId?: string; scope?: 'OPEN' | 'ALL'; search?: string } = {}): Observable<SchoolCashReceipt[]> {
    return this.http
      .get<ApiSuccessResponse<SchoolCashReceipt[]>>(`${BASE_URL}/receipts`, { params: toParams(filters) })
      .pipe(map((r) => r.data));
  }

  getTransfers(range: SchoolCashRange = {}): Observable<SchoolCashPage<SchoolCashTransfer>> {
    return this.http
      .get<ApiSuccessResponse<SchoolCashPage<SchoolCashTransfer>>>(`${BASE_URL}/transfers`, { params: toParams(range) })
      .pipe(map((r) => r.data));
  }

  registerTransfer(body: {
    bankId: string;
    items: { movementId: string; amount: number }[];
    reference?: string;
    observations?: string;
    clientRequestId: string;
  }): Observable<SchoolCashTransfer> {
    return this.http.post<ApiSuccessResponse<SchoolCashTransfer>>(`${BASE_URL}/transfers`, body).pipe(map((r) => r.data));
  }

  voidTransfer(id: string, reason: string): Observable<SchoolCashTransfer> {
    return this.http
      .post<ApiSuccessResponse<SchoolCashTransfer>>(`${BASE_URL}/transfers/${id}/void`, { reason })
      .pipe(map((r) => r.data));
  }

  getExits(range: SchoolCashRange = {}): Observable<SchoolCashPage<SchoolCashExit>> {
    return this.http
      .get<ApiSuccessResponse<SchoolCashPage<SchoolCashExit>>>(`${BASE_URL}/exits`, { params: toParams(range) })
      .pipe(map((r) => r.data));
  }

  registerExit(body: {
    amount: number;
    destination: SchoolCashExitDestination;
    bankId?: string;
    recipientName?: string;
    reason: string;
    reference?: string;
    clientRequestId: string;
  }): Observable<SchoolCashExit> {
    return this.http.post<ApiSuccessResponse<SchoolCashExit>>(`${BASE_URL}/exits`, body).pipe(map((r) => r.data));
  }

  voidExit(id: string, reason: string): Observable<SchoolCashExit> {
    return this.http.post<ApiSuccessResponse<SchoolCashExit>>(`${BASE_URL}/exits/${id}/void`, { reason }).pipe(map((r) => r.data));
  }

  registerAdjustment(body: {
    direction: 'IN' | 'OUT';
    amount: number;
    reason: string;
    clientRequestId: string;
  }): Observable<SchoolCashMovement> {
    return this.http.post<ApiSuccessResponse<SchoolCashMovement>>(`${BASE_URL}/adjustments`, body).pipe(map((r) => r.data));
  }

  voidAdjustment(movementId: string, reason: string): Observable<SchoolCashMovement> {
    return this.http
      .post<ApiSuccessResponse<SchoolCashMovement>>(`${BASE_URL}/movements/${movementId}/void`, { reason })
      .pipe(map((r) => r.data));
  }

  getCounts(range: SchoolCashRange = {}): Observable<SchoolCashPage<SchoolCashCount>> {
    return this.http
      .get<ApiSuccessResponse<SchoolCashPage<SchoolCashCount>>>(`${BASE_URL}/counts`, { params: toParams(range) })
      .pipe(map((r) => r.data));
  }

  registerCount(body: {
    details: { denomination: number; quantity: number }[];
    observations?: string;
    clientRequestId: string;
  }): Observable<SchoolCashCount> {
    return this.http.post<ApiSuccessResponse<SchoolCashCount>>(`${BASE_URL}/counts`, body).pipe(map((r) => r.data));
  }

  getReports(): Observable<SchoolCashReportInfo[]> {
    return this.http.get<ApiSuccessResponse<SchoolCashReportInfo[]>>(`${BASE_URL}/reports`).pipe(map((r) => r.data));
  }

  getReport(kind: string, range: { dateFrom?: string; dateTo?: string }): Observable<SchoolCashReport> {
    return this.http
      .get<ApiSuccessResponse<SchoolCashReport>>(`${BASE_URL}/reports/${kind}`, { params: toParams(range) })
      .pipe(map((r) => r.data));
  }

  exportReport(kind: string, format: 'pdf' | 'xlsx', range: { dateFrom?: string; dateTo?: string }): Observable<Blob> {
    return this.http.get(`${BASE_URL}/reports/${kind}/export`, {
      params: toParams({ ...range, format }),
      responseType: 'blob',
    });
  }
}
