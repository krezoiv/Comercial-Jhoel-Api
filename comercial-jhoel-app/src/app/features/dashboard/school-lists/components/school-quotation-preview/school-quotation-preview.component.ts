import { ChangeDetectionStrategy, Component, EventEmitter, Input, Output } from '@angular/core';

import { formatCurrency, formatSchoolDate } from '../../../../../core/models';
import { FocusTrapDirective } from '../../../../../shared/directives/focus-trap.directive';
import { IconComponent } from '../../../../../shared/ui';

/** What the customer document will show, built by the editor from its current state. */
export interface QuotationPreviewData {
  /** Saved number, or null for a quotation not saved yet. */
  number: string | null;
  statusLabel: string;
  date: string;
  deliveryDate: string | null;
  customerName: string;
  customerPhone: string;
  studentName: string | null;
  grade: string;
  observations: string | null;
  lines: { name: string; quantity: number; unitPrice: number; discount: number; subtotal: number }[];
  subtotal: number;
  discount: number;
  total: number;
  paid: number;
  /** "Anticipo" for a new quotation, "Pagado" for a saved one. */
  paidLabel: string;
  balance: number;
}

/**
 * "Vista previa" of the POS quotation window: the quotation laid out like the
 * document the customer receives (school requirements only, never inventory
 * products), from the unsaved data on screen. It is read-only and does not
 * call the API; the official PDF is generated by the backend from saved data.
 */
@Component({
  selector: 'app-school-quotation-preview',
  standalone: true,
  imports: [FocusTrapDirective, IconComponent],
  templateUrl: './school-quotation-preview.component.html',
  styleUrl: './school-quotation-preview.component.scss',
  changeDetection: ChangeDetectionStrategy.OnPush,
})
export class SchoolQuotationPreviewComponent {
  @Input({ required: true }) data!: QuotationPreviewData;
  @Output() closed = new EventEmitter<void>();

  readonly formatCurrency = formatCurrency;
  readonly formatDate = formatSchoolDate;
}
